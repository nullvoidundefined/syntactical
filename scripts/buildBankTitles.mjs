// Build step for the crawlable bank pages: reads every bank the content manifest lists and writes
// services/content/bankTitles.generated.ts with each bank's question count and its distinct
// query.title values in bank order. Titles are written not to give answers away, so they are the
// only question text that leaves the bank files here: never prompts, choices, answers,
// explanations, rationales, or syntax. Runs inside `npm run content:build`, after the manifest.
import { isSafeBankPath } from '@syntactical/content-schema';
import { realpathSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { pathToFileURL } from 'node:url';

const GENERATED_HEADER = `// GENERATED by scripts/buildBankTitles.mjs. Do not edit by hand.
// Run \`npm run content:build\` to regenerate it.
`;

function listBanks(manifest) {
  return manifest.languages.flatMap((language) =>
    Object.entries(language.banks).map(([difficulty, bank]) => ({
      key: `${language.id}/${difficulty}`,
      path: bank.path,
    })),
  );
}

// Each title once, at its first position: a bank repeats broad titles across questions.
function listDistinctTitles(questions) {
  return [...new Set(questions.map((question) => question.query.title))];
}

async function readBankSummary(contentDir, bankPath) {
  if (!isSafeBankPath(bankPath)) throw new Error(`${bankPath} is not a safe bank path`);
  const bank = JSON.parse(await readFile(join(contentDir, bankPath), 'utf8'));
  return { questionCount: bank.questions.length, titles: listDistinctTitles(bank.questions) };
}

function renderSource(entries) {
  const sorted = [...entries].sort((left, right) => (left.key < right.key ? -1 : 1));
  const countLines = sorted.map(({ key, summary }) => `  ${JSON.stringify(key)}: ${summary.questionCount},`);
  const titleLines = sorted.map(({ key, summary }) => `  ${JSON.stringify(key)}: ${JSON.stringify(summary.titles)},`);
  return `${GENERATED_HEADER}
export const BANK_QUESTION_COUNTS: Readonly<Record<string, number>> = {
${countLines.join('\n')}
};

export const BANK_TITLES: Readonly<Record<string, readonly string[]>> = {
${titleLines.join('\n')}
};
`;
}

export async function buildBankTitles(contentDir, outputPath) {
  const manifest = JSON.parse(await readFile(join(contentDir, 'manifest.json'), 'utf8'));
  const entries = await Promise.all(
    listBanks(manifest).map(async ({ key, path }) => ({ key, summary: await readBankSummary(contentDir, path) })),
  );
  await writeFile(outputPath, renderSource(entries));
  return entries.length;
}

// Compare as file URLs: a plain string compare breaks on a path with a space, and a symlink needs
// its real path.
if (process.argv[1] && import.meta.url === pathToFileURL(realpathSync(process.argv[1])).href) {
  const repoDir = process.cwd();
  buildBankTitles(join(repoDir, 'content'), join(repoDir, 'services/content/bankTitles.generated.ts')).catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}
