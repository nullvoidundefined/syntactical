// Build step for the content bundle: hashes every question bank into
// content/manifest.json, validates banks and manifest with the app's own
// validators, and generates the TypeScript modules that bundle them offline:
// one exporting the manifest and one exporting the bank require map.
import { CONTENT_LIMITS, buildBankContext, isSafeBankPath, validateManifest, validateQuestionBank } from '@syntactical/content-schema';
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join, relative, sep } from 'node:path';

import { summarizeBanks } from '../services/quality/summarizeBanks.ts';
import { summarizeReport } from '../services/quality/summarizeReport.ts';

const UTF8_BYTE_ORDER_MARK = [0xef, 0xbb, 0xbf];
const GENERATED_HEADER = `// GENERATED by scripts/buildContentManifest.mjs. Do not edit by hand.
// Run \`npm run content:build\` to regenerate it.
`;

function hasByteOrderMark(bytes) {
  return UTF8_BYTE_ORDER_MARK.every((byte, index) => bytes[index] === byte);
}

function listBankEntries(manifest) {
  return manifest.languages.flatMap((language) =>
    Object.entries(language.banks).map(([difficulty, bank]) => ({ language, difficulty, bank })),
  );
}

async function readBankBytes(contentDir, bankPath) {
  if (!isSafeBankPath(bankPath)) throw new Error(`${bankPath} is not a safe bank path`);
  const bytes = await readFile(join(contentDir, bankPath));
  if (bytes.length > CONTENT_LIMITS.bankBytes) {
    throw new Error(`${bankPath} is over the ${CONTENT_LIMITS.bankBytes} byte limit`);
  }
  if (hasByteOrderMark(bytes)) throw new Error(`${bankPath} starts with a UTF-8 byte-order mark`);
  return bytes;
}

function buildLanguageContext(bankPath, language) {
  if (!Array.isArray(language.topics) || !Array.isArray(language.misconceptions)) {
    throw new Error(`manifest.json is invalid: ${language.id} has no topics or misconceptions for ${bankPath}`);
  }
  return buildBankContext(language);
}

function assertValidBank(bankPath, bytes, language) {
  const result = validateQuestionBank(JSON.parse(bytes.toString('utf8')), buildLanguageContext(bankPath, language));
  if (!result.isValid) throw new Error(`${bankPath} is invalid: ${result.rule}`);
  if (result.droppedQuestionIds.length > 0) {
    throw new Error(`${bankPath} has invalid questions: ${result.droppedQuestionIds.join(', ')}`);
  }
}

async function hashBank(contentDir, bank, language) {
  const bytes = await readBankBytes(contentDir, bank.path);
  assertValidBank(bank.path, bytes, language);
  return createHash('sha256').update(bytes).digest('hex');
}

async function hashAllBanks(contentDir, manifest) {
  await Promise.all(
    listBankEntries(manifest).map(async ({ bank, language }) => {
      bank.hash = await hashBank(contentDir, bank, language);
    }),
  );
}

// Names an unsafe bank path before anything else, so the error points at the
// path itself and no file outside the content directory is ever read.
function assertSafeBankPaths(manifest) {
  for (const language of Array.isArray(manifest?.languages) ? manifest.languages : []) {
    for (const bank of Object.values(language?.banks ?? {})) {
      const bankPath = bank?.path;
      if (typeof bankPath === 'string' && !isSafeBankPath(bankPath)) {
        throw new Error(`${bankPath} is not a safe bank path`);
      }
    }
  }
}

// Validates the manifest's shape before any bank is read, so a malformed entry
// reports the manifest rule instead of failing deep in hashing. Hashes are
// recomputed afterwards, so stale or empty ones are replaced for this check.
function withPlaceholderHashes(manifest) {
  const copy = structuredClone(manifest);
  if (!Array.isArray(copy?.languages)) return copy;
  for (const language of copy.languages) {
    for (const bank of Object.values(language?.banks ?? {})) {
      if (bank && typeof bank === 'object') bank.hash = '0'.repeat(64);
    }
  }
  return copy;
}

function assertValidManifest(manifest) {
  const result = validateManifest(manifest);
  if (!result.isValid) throw new Error(`manifest.json is invalid: ${result.rule}`);
}

function toRequirePath(fromPath, targetPath) {
  const relativePath = relative(dirname(fromPath), targetPath).split(sep).join('/');
  return relativePath.startsWith('.') ? relativePath : `./${relativePath}`;
}

function renderManifestSource(requirePath, isTyped) {
  const typeImport = isTyped ? "\nimport type { Manifest } from '@syntactical/content-schema';\n" : '';
  const typeCast = isTyped ? ' as Manifest' : '';
  return `${GENERATED_HEADER}${typeImport}
export const BUNDLED_MANIFEST = require('${requirePath}')${typeCast};
`;
}

function renderBanksSource(bankLines, hasHeader) {
  return `${hasHeader ? `${GENERATED_HEADER}\n` : ''}export const BUNDLED_BANKS: Record<string, unknown> = {
${bankLines.join('\n')}
};
`;
}

function listBankLines(contentDir, banksPath, manifest) {
  return listBankEntries(manifest)
    .map(({ language, difficulty, bank }) => ({
      key: `${language.id}/${difficulty}`,
      requirePath: toRequirePath(banksPath, join(contentDir, bank.path)),
    }))
    .sort((left, right) => (left.key < right.key ? -1 : 1))
    .map(({ key, requirePath }) => `  '${key}': require('${requirePath}'),`);
}

// `outputs` is either one module path (a single module exporting both the
// manifest and the banks) or { banksPath, manifestPath } (one export per file).
async function writeGeneratedModules(contentDir, outputs, manifest) {
  const isSplit = typeof outputs !== 'string';
  const banksPath = isSplit ? outputs.banksPath : outputs;
  const manifestPath = isSplit ? outputs.manifestPath : outputs;
  const manifestRequirePath = toRequirePath(manifestPath, join(contentDir, 'manifest.json'));
  const bankLines = listBankLines(contentDir, banksPath, manifest);
  await mkdir(dirname(manifestPath), { recursive: true });
  await mkdir(dirname(banksPath), { recursive: true });
  if (!isSplit) {
    const manifestSource = renderManifestSource(manifestRequirePath, false);
    await writeFile(outputs, `${manifestSource}\n${renderBanksSource(bankLines, false)}`);
    return;
  }
  await writeFile(manifestPath, renderManifestSource(manifestRequirePath, true));
  await writeFile(banksPath, renderBanksSource(bankLines, true));
}

async function readPipelineReport(reportPath) {
  try {
    return JSON.parse(await readFile(reportPath, 'utf8'));
  } catch (err) {
    // No committed report yet: the quality page shows its "not audited yet" state.
    if (err?.code === 'ENOENT') return undefined;
    throw err;
  }
}

// The closed set of verdicts in pipeline/src/types/ValidationResult.ts.
const REPORT_STATUSES = ['passed', 'failed', 'not-executable'];

// The closed set of failure reasons in pipeline/src/types/ValidationResult.ts.
// Free text never reaches the public bundle through `reason`.
const REPORT_REASONS = ['answer-mismatch', 'ambiguous', 'nondeterministic', 'runner-error'];
const REPORT_STRING_MAX_LENGTH = 64;
const AGREEMENT_STAGE_PATTERN = /^[a-z-]{1,32}$/;

function isBoundedString(value) {
  return typeof value === 'string' && value.length <= REPORT_STRING_MAX_LENGTH;
}

function assertValidAgreement(agreement) {
  if (agreement === undefined) return;
  if (typeof agreement !== 'object' || agreement === null || Array.isArray(agreement)) {
    throw new Error('pipeline report agreement is not a plain object');
  }
  for (const [stage, rate] of Object.entries(agreement)) {
    if (!AGREEMENT_STAGE_PATTERN.test(stage)) throw new Error(`pipeline report agreement has an invalid stage name: ${stage.slice(0, 40)}`);
    if (typeof rate !== 'number' || !Number.isFinite(rate) || rate < 0 || rate > 1) {
      throw new Error(`pipeline report agreement for ${stage} is not a number from 0 to 1`);
    }
  }
}

function assertValidQuestion(question, manifestBankKeys) {
  if (!isBoundedString(question?.bankKey)) throw new Error('pipeline report has a question with no bankKey string');
  if (!manifestBankKeys.has(question.bankKey)) throw new Error('pipeline report has a question for a bank the manifest does not list');
  if (!REPORT_STATUSES.includes(question.status)) {
    throw new Error(`pipeline report has a question with an unknown status: ${String(question.status).slice(0, 40)}`);
  }
  if (question.reason !== undefined && !REPORT_REASONS.includes(question.reason)) {
    throw new Error('pipeline report has a question with an unknown reason');
  }
}

function assertValidReport(report, manifestBankKeys) {
  if (!isBoundedString(report?.runId)) throw new Error('pipeline report has no runId string');
  if (!isBoundedString(report.finishedAt)) throw new Error('pipeline report has no finishedAt string');
  if (!Array.isArray(report.questions)) throw new Error('pipeline report has no questions list');
  assertValidAgreement(report.agreement);
  for (const question of report.questions) assertValidQuestion(question, manifestBankKeys);
}

function assertEveryBankReported(manifest, report) {
  const manifestBankKeys = new Set(listBankEntries(manifest).map(({ language, difficulty }) => `${language.id}/${difficulty}`));
  assertValidReport(report, manifestBankKeys);
  const reported = new Set(report.questions.map(({ bankKey }) => bankKey));
  for (const bankKey of manifestBankKeys) {
    if (!reported.has(bankKey)) throw new Error(`missing report for ${bankKey}`);
  }
}

// Summarizes the committed pipeline report into the module the quality page
// imports; with no report it writes null, and with a report that skips a
// published bank it fails.
async function writeQualityModule({ outputPath, reportPath }, manifest) {
  const report = await readPipelineReport(reportPath);
  if (report !== undefined) assertEveryBankReported(manifest, report);
  const quality =
    report === undefined
      ? null
      : { banks: summarizeBanks(report), finishedAt: report.finishedAt, runId: report.runId, summary: summarizeReport(report) };
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(
    outputPath,
    `${GENERATED_HEADER}
import type { QualityReport } from './types/QualityReport';

export const QUALITY_REPORT: QualityReport | null = ${JSON.stringify(quality, null, 2)};
`,
  );
}

// `quality` is optional: { reportPath, outputPath } also writes the quality module.
export async function buildContentManifest(contentDir, outputs, quality) {
  const manifestPath = join(contentDir, 'manifest.json');
  const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
  assertSafeBankPaths(manifest);
  assertValidManifest(withPlaceholderHashes(manifest));
  await hashAllBanks(contentDir, manifest);
  assertValidManifest(manifest);
  const manifestText = `${JSON.stringify(manifest, null, 2)}\n`;
  if (Buffer.byteLength(manifestText, 'utf8') > CONTENT_LIMITS.manifestBytes) {
    throw new Error(`manifest.json is over the ${CONTENT_LIMITS.manifestBytes} byte limit`);
  }
  await writeFile(manifestPath, manifestText);
  await writeGeneratedModules(contentDir, outputs, manifest);
  if (quality) await writeQualityModule(quality, manifest);
}

if (import.meta.url === `file://${process.argv[1]}`) {
  buildContentManifest(
    'content',
    {
      banksPath: 'services/content/bundledBanks.generated.ts',
      manifestPath: 'services/content/bundledManifest.generated.ts',
    },
    { outputPath: 'services/quality/qualityReport.generated.ts', reportPath: 'pipeline/reports/latest.json' },
  ).catch((err) => {
    console.error(err);
    process.exitCode = 1;
  });
}
